"""users: accounts, login sessions, per-user preferences/stores, user_id on ratings and plans

Revision ID: 0002
Revises: 0001
Create Date: 2026-10-18

Expand-only (see DEPLOY.md): the old single-household `preferences` and `stores` tables stay
and `user_id` is nullable, so the previous image keeps working on this schema. Existing rows
stay unowned (NULL) until claimed with `python -m app.users create <name> --claim-existing`.
A later migration (contract) drops the old tables and makes user_id NOT NULL.
"""

from alembic import op

revision = "0002"
down_revision = "0001"
branch_labels = None
depends_on = None

SCHEMA = """
-- Usernames are never stored: only HMAC-SHA256(USERNAME_KEY, normalized username), keyed with
-- a secret that lives outside the database, so a leaked DB or backup doesn't reveal who has an
-- account (app/auth.py). Normalization makes "Claes" and "claes" the same account.
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username_hash TEXT        NOT NULL UNIQUE,
    password_hash TEXT        NOT NULL,  -- argon2id (app/auth.py)
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- One row per signed-in browser/device. Only the SHA-256 of the cookie token is stored, so a
-- leaked database or backup can't be replayed as a login.
CREATE TABLE sessions (
    token_hash   TEXT        PRIMARY KEY,
    user_id      BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at   TIMESTAMPTZ NOT NULL,
    persistent   BOOLEAN     NOT NULL,  -- "keep me signed in": cookie survives browser restarts
    user_agent   TEXT
);
CREATE INDEX sessions_user ON sessions (user_id);

-- per-user replacements for the single-household `preferences` (id = 1) and `stores` tables
CREATE TABLE user_preferences (
    user_id       BIGINT  PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    max_kcal      INTEGER,
    min_protein_g INTEGER,
    restrictions  TEXT    NOT NULL DEFAULT '',
    servings      INTEGER NOT NULL DEFAULT 2,
    bans          TEXT    NOT NULL DEFAULT '[]',  -- JSON list of banned category ids + custom items
    language      TEXT    NOT NULL DEFAULT ''     -- display language; '' = English
);
CREATE TABLE user_stores (
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    chain_slug TEXT   NOT NULL,
    PRIMARY KEY (user_id, chain_slug)
);

ALTER TABLE ratings ADD COLUMN user_id BIGINT REFERENCES users(id);
ALTER TABLE plans   ADD COLUMN user_id BIGINT REFERENCES users(id);
CREATE INDEX ratings_user ON ratings (user_id);
CREATE INDEX plans_user   ON plans (user_id, id);
"""

_DROP = """
DROP INDEX plans_user;
DROP INDEX ratings_user;
ALTER TABLE plans   DROP COLUMN user_id;
ALTER TABLE ratings DROP COLUMN user_id;
DROP TABLE user_stores, user_preferences, sessions, users;
"""


def upgrade() -> None:
    op.execute(SCHEMA)


def downgrade() -> None:
    op.execute(_DROP)
